import { toCsv } from './csv.mjs';
import { pathOf, resolveFinal } from './map.mjs';

const isRedirect = (e) => [301, 302, 307, 308].includes(e.status);

// Cloudflare Bulk Redirects list (Dashboard > Rules > Redirect Lists > Import CSV)
function cloudflareBulk(entries) {
  const rows = entries.filter(isRedirect).map((e) => ({
    source_url: e.oldUrl.replace(/^https?:\/\//, ''),
    target_url: e.newUrl,
    status_code: e.status,
    preserve_query_string: 'TRUE',
    include_subdomains: 'FALSE',
    subpath_matching: 'FALSE',
    preserve_path_suffix: 'FALSE',
  }));
  return toCsv(rows, Object.keys(rows[0] ?? { source_url: '', target_url: '', status_code: '' }));
}

// Cloudflare Pages / Netlify style _redirects file
function redirectsFile(entries) {
  return entries
    .filter(isRedirect)
    .map((e) => `${pathOf(e.oldUrl)} ${sameOrigin(e) ? pathOf(e.newUrl) : e.newUrl} ${e.status}`)
    .join('\n');
}

// Next.js next.config redirects() array
function nextjs(entries) {
  const items = entries.filter(isRedirect).map((e) => ({
    source: decodeSafe(new URL(e.oldUrl).pathname),
    destination: sameOrigin(e) ? decodeSafe(pathOf(e.newUrl)) : e.newUrl,
    permanent: e.status === 301 || e.status === 308,
  }));
  return `// Generated by seo-migration-toolkit. Paste into next.config redirects().\nexport const redirects = ${JSON.stringify(items, null, 2)};\n`;
}

function sameOrigin(e) {
  return new URL(e.oldUrl).host === new URL(e.newUrl).host;
}

function decodeSafe(p) {
  try {
    return decodeURI(p);
  } catch {
    return p;
  }
}

export const FORMATS = {
  'cloudflare-bulk': cloudflareBulk,
  'redirects-file': redirectsFile,
  nextjs,
};

export function exportMap(entries, format) {
  const fn = FORMATS[format];
  if (!fn) throw new Error(`Unknown format "${format}". Use: ${Object.keys(FORMATS).join(', ')}`);
  return fn(resolveFinal(entries));
}
